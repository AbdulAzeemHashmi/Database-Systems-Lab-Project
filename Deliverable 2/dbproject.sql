CREATE TRIGGER trg_GenerateEarningsOnCompletion
AFTER UPDATE ON Rides
FOR EACH ROW
BEGIN
    -- Only trigger when a ride is completed
    IF NEW.Ride_Status = 'Completed' AND OLD.Ride_Status <> 'Completed' THEN
        -- Check if a fare was calculated/set
        IF NEW.Fare IS NOT NULL AND NEW.Fare > 0 THEN
            INSERT INTO DriverEarnings (
                driver_id, 
