-- 1. User Table
CREATE TABLE User (
    user_id INT AUTO_INCREMENT PRIMARY KEY,
    Full_Name VARCHAR(100) NOT NULL,
    Email VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role           ENUM('Admin','Rider','Driver') NOT NULL,
    Phone_Number VARCHAR(20) UNIQUE,
    accountStatus ENUM('Active', 'Suspended', 'Banned', 'Flagged') DEFAULT 'Active',  -- enum means that this attribute can only have value from these three options
    CreatedOn DATETIME DEFAULT CURRENT_TIMESTAMP -- automatically input current date and time
);

-- 2. Driver Table (child of user)
CREATE TABLE Driver (
    driver_id INT PRIMARY KEY,
    Licence_No VARCHAR(50) NOT NULL UNIQUE,
    CNIC VARCHAR(20) NOT NULL UNIQUE,
    Profile_pic VARCHAR(255),
    Verification_Status ENUM('Pending', 'Verified', 'Rejected') DEFAULT 'Pending',
    Availability_Status ENUM('Offline', 'Online', 'On trip') DEFAULT 'Offline',
    Total_Trips INT DEFAULT 0 CHECK (Total_Trips >= 0),
    Average_Rating DECIMAL(3,2) DEFAULT 0.00 CHECK (Average_Rating BETWEEN 0 AND 5),  -- between 0.0 to 5.0
    CONSTRAINT fk_driver_user FOREIGN KEY (driver_id) REFERENCES User(user_id) ON DELETE CASCADE -- driverid is userid in user table. if user deleted, driver also deleted
);

-- 3. Rider Table (child of user)
CREATE TABLE Rider (
    rider_id INT PRIMARY KEY,
    Average_Rating DECIMAL(3,2) DEFAULT 0.00 CHECK (Average_Rating BETWEEN 0 AND 5),
    CONSTRAINT fk_rider_user FOREIGN KEY (rider_id) REFERENCES User(user_id) ON DELETE CASCADE  -- riderid is userid in user table. if user deleted, rider also deleted
);

-- 4. Admin Table (Specialization of User)
CREATE TABLE Admin (
    AdminID INT PRIMARY KEY,
    CONSTRAINT fk_admin_user FOREIGN KEY (AdminID) REFERENCES User(user_id) ON DELETE CASCADE -- adminid is userid in usertable. if user deleted, admin also deleted
);

-- 5. Vehicle Table
CREATE TABLE Vehicle (
    vehicle_id INT AUTO_INCREMENT PRIMARY KEY,
    driver_id INT NOT NULL,   -- each vehicle has exactly one driver
    make VARCHAR(50) NOT NULL,
    Model VARCHAR(50) NOT NULL,
    Color VARCHAR(30),
    License_Plate VARCHAR(20) NOT NULL UNIQUE,
	vehicle_type        ENUM('Economy','Premium','Bike') NOT NULL,
    Verification_Status ENUM('Pending', 'Verified', 'Rejected') DEFAULT 'Pending',
    year                YEAR        NOT NULL,
	CONSTRAINT check_vehicle_year   CHECK       (year >= 1990 AND year <= 2026),
    CONSTRAINT fk_vehicle_driver FOREIGN KEY (driver_id) REFERENCES Driver(driver_id) ON DELETE CASCADE -- id driver deleted, vehicle also deleted
);

-- 6. Location Table
CREATE TABLE Location (
    location_id INT AUTO_INCREMENT PRIMARY KEY,
    Address TEXT NOT NULL,
    Latitude DECIMAL(10, 8) NOT NULL,
    Longitude DECIMAL(11, 8) NOT NULL,
    City VARCHAR(50) NOT NULL,
    Country VARCHAR(50) NOT NULL,
	CONSTRAINT check_location_latitude  CHECK       (latitude  BETWEEN -90.0000000  AND  90.0000000),
    CONSTRAINT check_location_longitude CHECK       (longitude BETWEEN -180.0000000 AND 180.0000000)
);

-- 7. PromoCode Table
CREATE TABLE PromoCode (
    promo_id INT AUTO_INCREMENT PRIMARY KEY,
    AdminID INT NOT NULL, -- generated by one and only admin
    Code VARCHAR(20) NOT NULL UNIQUE,
    Discount_Type ENUM('Percentage', 'Flat') NOT NULL,
    Discount_Value DECIMAL(10, 2) NOT NULL CHECK (Discount_Value > 0),
    Usage_Limit INT DEFAULT 1 CHECK (Usage_Limit > 0),
    usage_count    INT           NOT NULL DEFAULT 0,
    Expiry_Date DATETIME NOT NULL,
    Min_Fare DECIMAL(10, 2) DEFAULT 0.00 CHECK (min_fare >= 0),
    CONSTRAINT fk_promo_admin FOREIGN KEY (AdminID) REFERENCES Admin(AdminID)  -- admin generates promocode, even if admin is deleted, promocode remains
);

CREATE TABLE FarePricing (
    pricing_id      INT AUTO_INCREMENT PRIMARY KEY,
    city            VARCHAR(100) NOT NULL,
    vehicle_type    ENUM('Economy','Premium','Bike') NOT NULL,
    base_rate       DECIMAL(10,2) NOT NULL,
    per_km_rate     DECIMAL(10,2) NOT NULL,
    per_minute_rate DECIMAL(10,2) NOT NULL,
    surge_multiplier DECIMAL(4,2) DEFAULT 1.00
);
-- 8. Rides Table
CREATE TABLE Rides (
    ride_id INT AUTO_INCREMENT PRIMARY KEY,
    rider_id INT NOT NULL,  -- every ride has exactly one rider
    driver_id INT, -- NULL if no driver accepts
    vehicle_id INT, -- NULL if no driver accepts
    pickup_loc_id INT NOT NULL,
    drop_loc_id INT NOT NULL,
    Ride_Status ENUM('Requested', 'Accepted', 'Driver En route','In progress', 'Completed', 'Cancelled') DEFAULT 'Requested',
    Fare DECIMAL(10, 2) CHECK (Fare >= 0),
    Distance DECIMAL(10, 2) COMMENT 'Distance in KM',
    Duration_in_minutes Int CHECK (Duration_in_minutes >=0),
    Scheduled_At DATETIME,
    Requested_At DATETIME DEFAULT CURRENT_TIMESTAMP,
    Started_At DATETIME,
    End_Time DATETIME,
        CONSTRAINT fk_rides_rider     FOREIGN KEY (rider_id)
        REFERENCES Rider(rider_id)
        ON DELETE RESTRICT ON UPDATE CASCADE, -- cant delete a rider if his rides exist, if rider id updated in rider, also update in rides
    CONSTRAINT fk_rides_driver    FOREIGN KEY (driver_id)
        REFERENCES Driver(driver_id)
        ON DELETE SET NULL ON UPDATE CASCADE, -- if driver deleted set NULL here, if updated update here too
    CONSTRAINT fk_rides_vehicle   FOREIGN KEY (vehicle_id)
        REFERENCES Vehicle(vehicle_id)
        ON DELETE SET NULL ON UPDATE CASCADE,   -- if vehicle deleted set NULL, if updated update here too
    CONSTRAINT fk_rides_pickup    FOREIGN KEY (pickup_loc_id)
        REFERENCES Location(location_id)
        ON DELETE RESTRICT ON UPDATE CASCADE, -- cant delete a location if it is being used in rides, if updated update here too
    CONSTRAINT fk_rides_drop      FOREIGN KEY (drop_loc_id)
        REFERENCES Location(location_id)
        ON DELETE RESTRICT ON UPDATE CASCADE  -- cant delete a location if it is being used in rides, if updated update here too
);


-- 9. Payment Table
CREATE TABLE Payment (
