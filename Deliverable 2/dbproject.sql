                gross_amount, 
                commission_amount, 
                net_amount
            )
            VALUES (
                NEW.driver_id, 
                NEW.ride_id, 
                NEW.Fare, 
                NEW.Fare * 0.20, -- Platform takes 20% commission
                NEW.Fare * 0.80  -- Driver receives 80% net earning
            );
        END IF;
    END IF;
END$$

