    Status ENUM('Pending', 'Completed', 'Failed','Refunded') DEFAULT 'Pending',
    Date DATETIME DEFAULT CURRENT_TIMESTAMP,
    Method ENUM('Cash', 'Credit Card', 'Wallet') NOT NULL,
	CONSTRAINT fk_payment_ride      FOREIGN KEY (ride_id)
        REFERENCES Rides(ride_id)
        ON DELETE CASCADE ON UPDATE CASCADE, -- cant delete a ride if payments exist
    CONSTRAINT fk_payment_rider     FOREIGN KEY (rider_id)
