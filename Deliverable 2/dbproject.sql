-- flag if rider rating below 3.0
DELIMITER $$

CREATE TRIGGER trg_UpdateRiderAndFlag
AFTER INSERT ON Rating
FOR EACH ROW
BEGIN
    DECLARE v_avg DECIMAL(3,2);
    DECLARE v_role ENUM('Admin','Rider','Driver');

    -- Identify if the rated user is a Rider
    SELECT role INTO v_role FROM User WHERE user_id = NEW.rated_user_id;

    IF v_role = 'Rider' THEN
        -- Recalculate Average 
        SELECT AVG(Score) INTO v_avg FROM Rating WHERE rated_user_id = NEW.rated_user_id;

        -- Update Rider Table
        UPDATE Rider SET average_rating = v_avg WHERE rider_id = NEW.rated_user_id;

        -- Flag if below 3.0 
        IF v_avg < 3.0 THEN
            UPDATE User SET accountStatus = 'Flagged' WHERE user_id = NEW.rated_user_id;
            
            INSERT INTO AdminNotification (message, related_user_id)
            VALUES (CONCAT('Rider Quality Warning: Rider ID ', NEW.rated_user_id, ' rating is ', v_avg), NEW.rated_user_id);
        END IF;
    END IF;
END$$

DELIMITER ;

-- flag driver if average rating falls below 3.5
DELIMITER $$

CREATE TRIGGER trg_UpdateDriverAndFlag
AFTER INSERT ON Rating
FOR EACH ROW
BEGIN
    DECLARE v_avg DECIMAL(3,2);
    DECLARE v_role ENUM('Admin','Rider','Driver');

    -- Identify if the rated user is a Driver
    SELECT role INTO v_role FROM User WHERE user_id = NEW.rated_user_id;

    IF v_role = 'Driver' THEN
        -- Recalculate Average 
        SELECT AVG(Score) INTO v_avg FROM Rating WHERE rated_user_id = NEW.rated_user_id;

        -- Update Driver Table
        UPDATE Driver SET Average_Rating = v_avg WHERE driver_id = NEW.rated_user_id;

        -- Flag if below 3.5
        IF v_avg < 3.5 THEN
            UPDATE User SET accountStatus = 'Flagged' WHERE user_id = NEW.rated_user_id;
            
            INSERT INTO AdminNotification (message, related_user_id)
            VALUES (CONCAT('Low Rating Alert: Driver ID ', NEW.rated_user_id, ' has dropped to ', v_avg), NEW.rated_user_id);
        END IF;
    END IF;
END$$

