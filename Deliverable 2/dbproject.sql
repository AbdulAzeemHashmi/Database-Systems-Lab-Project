-- create view for revenue by city reporting
CREATE OR REPLACE VIEW vw_RevenueByCity AS
SELECT 
    l.City, p.Date AS payment_date,
    COUNT(r.ride_id) AS Total_Rides,
    SUM(p.Amount) AS Gross_Revenue,
    SUM(de.commission_amount) AS Platform_Commission
FROM Rides r
JOIN Payment p ON r.ride_id = p.ride_id
JOIN DriverEarnings de ON r.ride_id = de.ride_id
JOIN Location l ON r.pickup_loc_id = l.location_id
WHERE r.Ride_Status = 'Completed'
GROUP BY l.City, p.Date;

-- create view for top rating drivers according to reviews for each city
CREATE OR REPLACE VIEW vw_DriverLeaderboard AS
SELECT 
    l.City,
    u.Full_Name,
    d.Average_Rating,
    d.Total_Trips
FROM Driver d
JOIN User u ON d.driver_id = u.user_id
JOIN Rides r ON r.driver_id = d.driver_id
JOIN Location l ON r.pickup_loc_id = l.location_id
WHERE d.Verification_Status = 'Verified'
GROUP BY l.City, d.driver_id
ORDER BY l.City, d.Average_Rating DESC;

CREATE OR REPLACE VIEW vw_RevenueByMethod AS
SELECT Method, SUM(Amount) AS Total, COUNT(*) AS Transactions
FROM Payment WHERE Status = 'Completed'
GROUP BY Method;

CREATE OR REPLACE VIEW vw_Refunds AS
SELECT COUNT(*) AS Total_Refunds, SUM(Amount) AS Refund_Total
FROM Payment WHERE Status = 'Refunded';

CREATE OR REPLACE VIEW vw_DriverEarningsSummary AS
SELECT driver_id, SUM(gross_amount) AS Total_Gross,
       SUM(commission_amount) AS Total_Commission,
       SUM(net_amount) AS Net_Earnings
FROM DriverEarnings GROUP BY driver_id;

