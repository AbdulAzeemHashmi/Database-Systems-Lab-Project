-- process to calculate fare pricing
DELIMITER $$

CREATE PROCEDURE sp_CalculateFare(
    IN  p_city          VARCHAR(100),
    IN  p_vehicle_type  ENUM('Economy','Premium','Bike'),
    IN  p_distance_km   DECIMAL(10,2),
    IN  p_duration_min  INT,
    IN  p_is_surge      TINYINT, -- 1 for active surge, 0 for normal
    OUT p_final_fare    DECIMAL(10,2)
)
BEGIN
    DECLARE v_base_rate DECIMAL(10,2);
    DECLARE v_per_km    DECIMAL(10,2);
    DECLARE v_per_min   DECIMAL(10,2);
    DECLARE v_surge     DECIMAL(4,2);

    -- Lookup rates from FarePricing table
    SELECT base_rate, per_km_rate, per_minute_rate, surge_multiplier
    INTO   v_base_rate, v_per_km, v_per_min, v_surge
    FROM   FarePricing
    WHERE  city = p_city AND vehicle_type = p_vehicle_type
    ORDER BY pricing_id DESC LIMIT 1;

    -- Formula 
    SET p_final_fare = v_base_rate + (v_per_km * p_distance_km) + (v_per_min * p_duration_min);

    -- Apply Surge 
    IF p_is_surge = 1 THEN
        SET p_final_fare = p_final_fare * v_surge;
    END IF;

    SET p_final_fare = ROUND(p_final_fare, 2);
END$$

