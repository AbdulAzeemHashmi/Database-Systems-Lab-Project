-- If paid through wallet, deduction
DELIMITER $$

CREATE TRIGGER trg_ProcessWalletPayment
BEFORE INSERT ON Payment
FOR EACH ROW
BEGIN
    IF NEW.Method = 'Wallet' THEN
        -- Ensure rider has enough balance 
        IF (SELECT balance FROM Wallet WHERE user_id = NEW.rider_id) < NEW.Amount THEN
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Insufficient wallet balance for this payment.';
        ELSE
            -- Deduct amount from Rider's wallet
            UPDATE Wallet 
            SET balance = balance - NEW.Amount 
            WHERE user_id = NEW.rider_id;
        END IF;
    END IF;
END$$

